#!/usr/bin/env python3
"""
Writes public/eggtips.js: every Egg SMP egg's item tooltip exactly as the game shows it (name,
Energy, Tier, passives and abilities with their numbers, the Soulbound line), at Level I and II, for
the "In-game description" on a player's egg card.

    python3 scripts/egg-tooltips.py [path to the Egg SMP datapack]

The datapack's own tools/generate_tooltips.py does the reading (each egg's item() in
src/main/java/com/eggsmp/eggs/*Egg.java, with the numbers from the config defaults), so this follows
the mod without a second copy of the text. Run it again after the datapack changes. By default the
datapack is looked for beside this repository (../Egg-SMP-Season-1-Datapack).

A line is a list of runs [text, color, style], style 1 = bold, 2 = italic, 3 = both.
"""
import importlib.util
import json
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
pack = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else HERE.parent.parent / "Egg-SMP-Season-1-Datapack"
tool = pack / "tools" / "generate_tooltips.py"
if not tool.exists():
    sys.exit(f"no tools/generate_tooltips.py in {pack}: pass the path to the Egg SMP datapack")

# The tool draws images with Pillow; only its reading half is used here, so Pillow needn't be installed.
if importlib.util.find_spec("PIL") is None:
    pil = types.ModuleType("PIL")
    pil.Image = pil.ImageDraw = pil.ImageFont = None
    sys.modules["PIL"] = pil
sys.path.insert(0, str(tool.parent))
spec = importlib.util.spec_from_file_location("generate_tooltips", tool)
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def runs(node):
    out = []
    for text, color, bold, italic, _shadow in node.runs():
        style = (1 if bold else 0) | (2 if italic else 0)
        color = gen.NAMED.get(color, color).upper()
        if out and out[-1][1] == color and out[-1][2] == style:
            out[-1][0] += text
        else:
            out.append([text, color, style])
    return out


eggs = {}
for path in sorted(gen.EGGS_DIR.glob("*Egg.java")):
    tiers = {}
    for tier in (1, 2):
        try:
            result = gen.read_egg(path, tier, 5)
        except (ValueError, IndexError) as e:
            sys.exit(f"{path.name}: {e}")
        if result is None:
            break
        egg, lines = result
        tiers[tier] = [runs(line) for line in lines]
    if tiers:
        eggs[egg] = tiers

# the part of the Energy line after "⚡ Energy: ", for each amount of energy
energy = {e: runs(gen.line(*parts)) for e, parts in gen.ENERGY_BAR.items()}

dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))
out = HERE.parent / "public" / "eggtips.js"
with out.open("w", encoding="utf-8") as f:
    f.write("// Generated by scripts/egg-tooltips.py from the Egg SMP datapack: do not edit by hand.\n")
    f.write("// Each egg's item tooltip as the game shows it, at Level I (1) and Level II (2), at full Energy:\n")
    f.write("// lines of runs [text, color, style] (style 1 = bold, 2 = italic). Line 0 is the name, line 1 the\n")
    f.write("// Energy line (EGG_TIP_ENERGY has what follows its label for each amount of energy), line 2 the Tier.\n")
    f.write("export const EGG_TIPS = {\n")
    for egg, tiers in eggs.items():
        f.write(f"  {json.dumps(egg)}: {{\n")
        for tier, lines in tiers.items():
            f.write(f"    {tier}: [\n")
            for line in lines:
                f.write(f"      {dump(line)},\n")
            f.write("    ],\n")
        f.write("  },\n")
    f.write("};\n\n")
    f.write(f"export const EGG_TIP_ENERGY = {dump({str(k): v for k, v in sorted(energy.items())})};\n")
print(f"wrote {len(eggs)} eggs to {out}", file=sys.stderr)
